#!/usr/bin/env python
"""Regenerate every demo fixture: sample inputs, depth maps, move thumbnails, example clips,
coverage stills, the stitched sequence, recipes and manifest.

    python scripts/make_fixtures.py            # everything (about 5-10 min, CPU only)
    python scripts/make_fixtures.py --quick    # 1 input, tiny: for CI/smoke tests

HONESTY: every clip/still produced here is a SIMULATED camera move (depth-parallax re-projection
of a procedurally generated image). It is a placeholder to be replaced by real model output
(LTX-2 / Router) once GPU or credits exist. See examples/CREDITS.md.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import angles, procart, vcam  # noqa: E402
from app.media import encode_frames, save_jpg  # noqa: E402
from app.presets import load_presets  # noqa: E402
from app.recipes import make_recipe, sha256_file  # noqa: E402
from app.stitch import stitch  # noqa: E402

INPUTS = ROOT / "examples" / "inputs"
OUT = ROOT / "examples" / "outputs"
THUMBS = ROOT / "examples" / "presets"
HERO_MOVES = ["dolly-in", "orbit-left", "jib-up"]
SEQUENCE = [("alpine-dusk", "dolly-in"), ("neon-rooftops", "orbit-left"), ("desert-monolith", "jib-up"), ("glass-orbs", "dolly-in")]
SIM = "SIMULATED placeholder (depth-parallax virtual camera). Not generative-model output."


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--clean", action="store_true")
    args = ap.parse_args()
    if args.clean:
        for d in (OUT, THUMBS):
            shutil.rmtree(d, ignore_errors=True)
    for d in (INPUTS, OUT / "clips", OUT / "coverage", OUT / "sequence", OUT / "recipes", THUMBS):
        d.mkdir(parents=True, exist_ok=True)
    presets = load_presets()
    arts = list(procart.ALL.items())[: 1 if args.quick else 4]
    items: list[dict] = []
    t_all = time.time()

    # 1. inputs + depth + meta
    scenes: dict[str, vcam.Scene] = {}
    art_by_id: dict[str, procart.Art] = {}
    for key, fn in arts:
        a = fn()
        art_by_id[a.id] = a
        save_jpg(a.rgb, INPUTS / f"{a.id}.jpg", quality=88)
        Image.fromarray((a.depth * 255).astype(np.uint8)).save(INPUTS / f"{a.id}_depth.png", optimize=True)
        (INPUTS / f"{a.id}.json").write_text(json.dumps({"id": a.id, "title": a.title, "file": f"{a.id}.jpg", "depth": f"{a.id}_depth.png", "subject": list(a.subject), "blurb": a.blurb, "license": "CC0-1.0 (procedurally generated by app/procart.py; no photos, people, brands or logos)"}, indent=2) + "\n")
        scenes[a.id] = vcam.Scene.from_images(Image.open(INPUTS / f"{a.id}.jpg"), Image.open(INPUTS / f"{a.id}_depth.png"))
        print("input", a.id)

    # 2. move thumbnails (all presets, from the first input)
    base_id = next(iter(art_by_id))
    for pid, p in presets.items():
        path = vcam.CameraPath.from_spec(p["virtual_camera"])
        out = THUMBS / f"{pid}.mp4"
        encode_frames(vcam.frames(scenes[base_id], path, 48, 384, 216), out, width=384, height=216, fps=24, crf=31)
        print("thumb", pid, out.stat().st_size // 1024, "KB")
        if args.quick and len(items) > 3:
            break

    # 3. hero clips
    for aid, art in art_by_id.items():
        for pid in HERO_MOVES:
            p = presets[pid]
            path = vcam.CameraPath.from_spec(p["virtual_camera"])
            out = OUT / "clips" / f"{aid}__{pid}.mp4"
            n = 24 * (2 if args.quick else 4)
            t0 = time.time()
            encode_frames(vcam.frames(scenes[aid], path, n, 1280, 720), out, width=1280, height=720, fps=24, crf=28)
            rec = make_recipe(kind="shot", engine="demo", model="vcam-depth-parallax", source_name=art.title, source_sha256=sha256_file(INPUTS / f"{aid}.jpg"), preset_id=pid, prompt=p["prompt_template"], negative=p.get("negative", ""), seed=7, params={"duration": n // 24, "resolution": "1280x720", "fps": 24, "crf": 28}, simulated=True, credits_used=0.0, extra={"note": SIM})
            rp = OUT / "recipes" / f"{aid}__{pid}.json"
            rp.write_text(json.dumps(rec, indent=2) + "\n")
            items.append({"id": f"{aid}__{pid}", "kind": "clip", "input": aid, "preset": pid, "file": f"clips/{aid}__{pid}.mp4", "recipe": f"recipes/{aid}__{pid}.json", "bytes": out.stat().st_size})
            print("clip", aid, pid, round(time.time() - t0, 1), "s", out.stat().st_size // 1024, "KB")

    # 4. coverage stills
    for aid, art in art_by_id.items():
        files = []
        for shot in angles.COVERAGE:
            cam = angles.angle_to_cam(shot["angle"], art.subject)
            dst = OUT / "coverage" / aid / f"{shot['id']}.jpg"
            save_jpg(vcam.render(scenes[aid], cam, 1280, 720), dst, quality=80)
            files.append({"id": shot["id"], "label": shot["label"], "file": f"coverage/{aid}/{shot['id']}.jpg", "qwen_prompt": angles.qwen_prompt(shot["angle"])})
        rec = make_recipe(kind="coverage", engine="demo", model="vcam-depth-parallax", source_name=art.title, source_sha256=sha256_file(INPUTS / f"{aid}.jpg"), seed=7, params={"shots": files}, simulated=True, credits_used=0.0, extra={"note": SIM})
        (OUT / "recipes" / f"{aid}__coverage.json").write_text(json.dumps(rec, indent=2) + "\n")
        items.append({"id": f"{aid}__coverage", "kind": "coverage", "input": aid, "files": files, "recipe": f"recipes/{aid}__coverage.json"})
        print("coverage", aid)

    # 5. stitched sequence
    picks = [(a, m) for a, m in SEQUENCE if a in art_by_id and (OUT / "clips" / f"{a}__{m}.mp4").is_file()]
    if picks:
        seq = OUT / "sequence" / "demo-sequence.mp4"
        stitch([OUT / "clips" / f"{a}__{m}.mp4" for a, m in picks], seq, crossfade=0.4)
        rec = make_recipe(kind="sequence", engine="demo", model="ffmpeg-xfade", source_name="4 simulated clips", source_sha256=None, simulated=True, params={"clips": [f"{a}__{m}" for a, m in picks], "crossfade_s": 0.4}, extra={"note": SIM})
        (OUT / "recipes" / "demo-sequence.json").write_text(json.dumps(rec, indent=2) + "\n")
        items.append({"id": "demo-sequence", "kind": "sequence", "file": "sequence/demo-sequence.mp4", "recipe": "recipes/demo-sequence.json", "bytes": seq.stat().st_size})
        print("sequence", seq.stat().st_size // 1024, "KB")

    (OUT / "manifest.json").write_text(json.dumps({"simulated": True, "note": SIM, "items": items}, indent=2) + "\n")
    total = sum(p.stat().st_size for d in (OUT, THUMBS, INPUTS) for p in d.rglob("*") if p.is_file())
    write_gallery(items, art_by_id)
    print(f"done in {time.time() - t_all:.0f}s; fixtures total {total / 1e6:.1f} MB")


def write_gallery(items: list[dict], arts: dict) -> None:
    lines = ["# Example gallery", "", "> **Every output below is a simulated placeholder.** Clips are depth-parallax re-projections of procedurally generated images (`app/vcam.py`), *not* output of LTX-2, Qwen, or any partner model. They exist so the app is fully demonstrable with zero keys, credits or GPU. They will be replaced by real model outputs (each with its own `recipe.json`) when credits/GPU exist. See [`CREDITS.md`](CREDITS.md).", ""]
    for aid, art in arts.items():
        lines += [f"## {art.title}", "", f"*{art.blurb}*", "", f"![input](inputs/{aid}.jpg)", ""]
        for it in items:
            if it["kind"] == "clip" and it["input"] == aid:
                lines.append(f"- **{it['preset']}**: [`outputs/{it['file']}`](outputs/{it['file']}) · [recipe](outputs/{it['recipe']})")
        cov = next((i for i in items if i["kind"] == "coverage" and i["input"] == aid), None)
        if cov:
            lines += ["", "Coverage board: " + " · ".join(f"[{f['label']}](outputs/{f['file']})" for f in cov["files"]), ""]
    seq = next((i for i in items if i["kind"] == "sequence"), None)
    if seq:
        lines += ["## Stitched sequence", "", f"[`outputs/{seq['file']}`](outputs/{seq['file']}): four simulated clips joined with 0.4 s crossfades by `app/stitch.py`.", ""]
    (ROOT / "examples" / "gallery.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
