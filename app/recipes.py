"""recipe.json: everything needed to reproduce (or honestly label) an output."""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import __version__


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_json(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def make_recipe(*, kind: str, engine: str, model: str, source_name: str, source_sha256: str | None, preset_id: str | None = None, prompt: str = "", negative: str = "", seed: int = 0, params: dict[str, Any] | None = None, workflow_sha256: str | None = None, simulated: bool = False, credits_used: float | None = None, extra: dict[str, Any] | None = None) -> dict[str, Any]:
    r: dict[str, Any] = {
        "schema": "shot-director/recipe@1",
        "app_version": __version__,
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "kind": kind,  # shot | reframe | coverage | sequence
        "engine": engine,  # demo | open | cloud | router
        "model": model,
        "simulated": simulated,
        "provenance": ("SIMULATED placeholder: depth-parallax virtual camera, not model output" if simulated else "generated by the model named in `model`"),
        "source": {"name": source_name, "sha256": source_sha256},
        "preset": preset_id,
        "prompt": prompt,
        "negative": negative,
        "seed": seed,
        "params": params or {},
        "workflow_sha256": workflow_sha256,
        "credits_used": credits_used,
    }
    if extra:
        r.update(extra)
    return r
